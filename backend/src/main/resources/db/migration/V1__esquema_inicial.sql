-- EduConnect - esquema inicial
-- Compatível com PostgreSQL (produção) e H2 em modo PostgreSQL (testes).

CREATE TABLE cursos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(20)  NOT NULL,
    codigo        VARCHAR(20)  NOT NULL,
    nome          VARCHAR(120) NOT NULL,
    carga_horaria INTEGER      NOT NULL,
    descricao     VARCHAR(1000),
    status        VARCHAR(20)  NOT NULL,
    sala          VARCHAR(60),
    plataforma    VARCHAR(120),
    criado_em     TIMESTAMP    NOT NULL,
    CONSTRAINT uk_cursos_codigo UNIQUE (codigo),
    CONSTRAINT ck_cursos_carga CHECK (carga_horaria > 0)
);

CREATE TABLE usuarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    login      VARCHAR(60)  NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil     VARCHAR(20)  NOT NULL,
    ativo      BOOLEAN      NOT NULL,
    criado_em  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuarios_login UNIQUE (login)
);

CREATE TABLE administradores (
    id BIGINT PRIMARY KEY,
    CONSTRAINT fk_administradores_usuario FOREIGN KEY (id) REFERENCES usuarios (id)
);

CREATE TABLE professores (
    id            BIGINT PRIMARY KEY,
    registro      VARCHAR(30)  NOT NULL,
    especialidade VARCHAR(120) NOT NULL,
    CONSTRAINT uk_professores_registro UNIQUE (registro),
    CONSTRAINT fk_professores_usuario FOREIGN KEY (id) REFERENCES usuarios (id)
);

CREATE TABLE alunos (
    id        BIGINT PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL,
    curso_id  BIGINT      NOT NULL,
    CONSTRAINT uk_alunos_matricula UNIQUE (matricula),
    CONSTRAINT fk_alunos_usuario FOREIGN KEY (id) REFERENCES usuarios (id),
    CONSTRAINT fk_alunos_curso FOREIGN KEY (curso_id) REFERENCES cursos (id)
);

CREATE TABLE professor_cursos (
    professor_id BIGINT NOT NULL,
    curso_id     BIGINT NOT NULL,
    PRIMARY KEY (professor_id, curso_id),
    CONSTRAINT fk_professor_cursos_professor FOREIGN KEY (professor_id) REFERENCES professores (id),
    CONSTRAINT fk_professor_cursos_curso FOREIGN KEY (curso_id) REFERENCES cursos (id)
);

CREATE TABLE turmas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(20) NOT NULL,
    curso_id          BIGINT      NOT NULL,
    professor_id      BIGINT,
    capacidade_maxima INTEGER     NOT NULL,
    status            VARCHAR(20) NOT NULL,
    criado_em         TIMESTAMP   NOT NULL,
    CONSTRAINT uk_turmas_codigo UNIQUE (codigo),
    CONSTRAINT ck_turmas_capacidade CHECK (capacidade_maxima > 0),
    CONSTRAINT fk_turmas_curso FOREIGN KEY (curso_id) REFERENCES cursos (id),
    CONSTRAINT fk_turmas_professor FOREIGN KEY (professor_id) REFERENCES professores (id)
);

CREATE TABLE turma_alunos (
    turma_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    PRIMARY KEY (turma_id, aluno_id),
    CONSTRAINT fk_turma_alunos_turma FOREIGN KEY (turma_id) REFERENCES turmas (id),
    CONSTRAINT fk_turma_alunos_aluno FOREIGN KEY (aluno_id) REFERENCES alunos (id)
);

CREATE TABLE avaliacoes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id       BIGINT        NOT NULL,
    turma_id       BIGINT        NOT NULL,
    descricao      VARCHAR(200)  NOT NULL,
    nota           NUMERIC(4, 2) NOT NULL,
    data_avaliacao DATE          NOT NULL,
    criado_em      TIMESTAMP     NOT NULL,
    atualizado_em  TIMESTAMP     NOT NULL,
    CONSTRAINT ck_avaliacoes_nota CHECK (nota >= 0 AND nota <= 10),
    CONSTRAINT fk_avaliacoes_aluno FOREIGN KEY (aluno_id) REFERENCES alunos (id),
    CONSTRAINT fk_avaliacoes_turma FOREIGN KEY (turma_id) REFERENCES turmas (id)
);

CREATE TABLE configuracao_academica (
    id                           BIGINT PRIMARY KEY,
    media_minima_aprovacao       NUMERIC(4, 2),
    media_minima_recuperacao     NUMERIC(4, 2),
    quantidade_minima_avaliacoes INTEGER   NOT NULL,
    atualizado_em                TIMESTAMP NOT NULL
);

CREATE TABLE atividades (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo      VARCHAR(40)  NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    usuario   VARCHAR(60),
    criado_em TIMESTAMP    NOT NULL
);

CREATE INDEX idx_usuarios_nome ON usuarios (nome);
CREATE INDEX idx_alunos_curso ON alunos (curso_id);
CREATE INDEX idx_turmas_curso ON turmas (curso_id);
CREATE INDEX idx_turmas_professor ON turmas (professor_id);
CREATE INDEX idx_avaliacoes_aluno ON avaliacoes (aluno_id);
CREATE INDEX idx_avaliacoes_turma ON avaliacoes (turma_id);
CREATE INDEX idx_atividades_criado ON atividades (criado_em);

